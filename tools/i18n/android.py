"""Generates android/app/src/main/res/values*/strings.xml from shared/i18n.

    python3 tools/i18n/android.py

Shared strings come from shared/i18n/<lang>.json (keys = English text). Android-only strings
come from ANDROID below and tools/i18n/tr_android.py. Resource names are slugs of the English
text, so code refers to them as R.string.<slug> (printed with --names).
"""
import importlib.util
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
I18N = os.path.join(ROOT, "shared", "i18n")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

# Android-only English strings (wording for phones instead of "this Mac", Bluetooth, etc.)
ANDROID = [
    "Turn the logger on and connect it with a USB OTG cable, or pair it over Bluetooth.",
    "Connect by USB",
    "Connect by Bluetooth",
    "Connected by Bluetooth",
    "Paired devices",
    "No paired Bluetooth devices. Pair the logger in the system Bluetooth settings (PIN 0000).",
    "Open Bluetooth settings",
    "All tracks on the logger will be erased after they are saved on this phone.",
    "Allow access to the logger when Android asks.",
    "Bluetooth permission is needed to talk to the logger.",
    "Downloading from the logger",
    "Settings",
    "Disconnect",
    "Save to file",
]

# Mac-only strings that Android does not use
SKIP = {
    "Turn the logger on and connect it to this Mac with a USB data cable. It will appear here automatically.",
    "All tracks on the logger will be erased after they are saved on this Mac.",
    "Show in Finder",
    "Can't open the logger's USB interface (IOKit error %@).",
    "No icon",
    "The new language is used after a restart.",
    "Restart now",
}

ANDROID_LOCALE = {"zh-Hans": "zh-rCN", "pt-BR": "pt-rBR", "id": "in"}


def slug(s: str) -> str:
    s = s.replace("%%", " percent ").replace("%@", " x ").replace("%lld", " n ").replace("≈", "about")
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").lower()
    s = s[:48].rstrip("_")
    if s in {"continue", "default", "new", "do", "for", "if", "switch", "case", "break", "return"}:
        s += "_action"
    return ("s_" + s) if not s or s[0].isdigit() else s


def convert(text: str) -> str:
    """Apple placeholders to Android positional ones, XML-escaped."""
    n = 0

    def ph(m):
        nonlocal n
        if m.group(0) == "%%":
            return "%%"
        n += 1
        return f"%{n}$s" if m.group(0) == "%@" else f"%{n}$d"

    out = re.sub(r"%%|%@|%lld", ph, text)
    out = out.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    out = out.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if out.startswith("@") or out.startswith("?"):
        out = "\\" + out
    return out


def load_android_translations():
    path = os.path.join(os.path.dirname(__file__), "tr_android.py")
    if not os.path.exists(path):
        return {}
    spec = importlib.util.spec_from_file_location("tr_android", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.T


def main():
    en = [k for k in json.load(open(os.path.join(I18N, "en.json"))) if k not in SKIP] + ANDROID
    names = {}
    for k in en:
        s = slug(k)
        base, i = s, 2
        while s in names.values():
            s = f"{base}_{i}"
            i += 1
        names[k] = s
    if "--names" in sys.argv:
        for k, v in names.items():
            print(f"{v}\t{k}")
        return
    atr = load_android_translations()
    langs = ["en"] + sorted(f[:-5] for f in os.listdir(I18N) if f.endswith(".json") and f != "en.json")
    for lang in langs:
        shared = {k: k for k in en} if lang == "en" else json.load(open(os.path.join(I18N, f"{lang}.json")))
        extra = dict(zip(ANDROID, atr.get(lang, ANDROID if lang == "en" else [])))
        lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/i18n/android.py. Do not edit. -->", "<resources>"]
        if lang == "en":
            lines.append('    <string name="app_name" translatable="false">A747 GPS Logger</string>')
        for k in en:
            v = shared.get(k) if k not in ANDROID else extra.get(k)
            if v is None:
                continue
            lines.append(f'    <string name="{names[k]}">{convert(v)}</string>')
        lines.append("</resources>\n")
        d = os.path.join(RES, "values" if lang == "en" else f"values-{ANDROID_LOCALE.get(lang, lang)}")
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "strings.xml"), "w").write("\n".join(lines))
    # locales for per-app language settings
    print(f"{len(langs)} locales, {len(en)} strings")


if __name__ == "__main__":
    main()
